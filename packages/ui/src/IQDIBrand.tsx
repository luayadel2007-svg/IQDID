import symbolLight from '../../../assets/branding/people-first/iqdi-symbol-light.svg?url';
import symbolDark from '../../../assets/branding/people-first/iqdi-symbol-dark.svg?url';
import symbolMono from '../../../assets/branding/people-first/iqdi-symbol-monochrome.svg?url';
import compactLight from '../../../assets/branding/people-first/iqdi-symbol-compact.svg?url';
import compactDark from '../../../assets/branding/people-first/iqdi-symbol-compact-dark.svg?url';
import primaryLight from '../../../assets/branding/people-first/iqdi-primary-light.svg?url';
import primaryDark from '../../../assets/branding/people-first/iqdi-primary-dark.svg?url';
import primaryMono from '../../../assets/branding/people-first/iqdi-primary-monochrome.svg?url';
import horizontalLight from '../../../assets/branding/people-first/iqdi-horizontal-light.svg?url';
import horizontalDark from '../../../assets/branding/people-first/iqdi-horizontal-dark.svg?url';
import horizontalMono from '../../../assets/branding/people-first/iqdi-horizontal-monochrome.svg?url';
import { useTheme } from './hooks.ts';

/**
 * The one IQDI brand component («People First — Human Centered»). The vector masters live in
 * assets/branding/people-first/ (generated by tools/branding/people_first.py); pages never copy artwork.
 *  - symbol:     the human symbol alone (head + blue band + gold leaf) — headers, about areas
 *  - compact:    the same symbol with flat colours and wider gaps — anything rendered ≤ 24 px
 *  - horizontal: symbol | IQDI + Arabic and English names — sidebars, institutional headers
 *  - logo:       primary vertical logo with the optional «People First • Human Centered» line — welcome screens
 *  - mark:       kept for compatibility; same as `symbol`
 * Light or Dark artwork follows the active theme unless `tone` fixes it; `monochrome` is black ink.
 * TEST ONLY project: the label never implies government endorsement.
 */
export type IQDIBrandVariant = 'symbol' | 'compact' | 'horizontal' | 'logo' | 'mark';
export const IQDI_BRAND_LABEL = 'IQDI — الهوية الرقمية العراقية (نموذج تجريبي)';

type Art = { light: string; dark: string; mono: string; ratio: number };
const SYMBOL: Art = { light: symbolLight, dark: symbolDark, mono: symbolMono, ratio: 660 / 640 };
const ART: Record<IQDIBrandVariant, Art> = {
  symbol: SYMBOL,
  mark: SYMBOL,
  compact: { light: compactLight, dark: compactDark, mono: symbolMono, ratio: 660 / 640 },
  horizontal: { light: horizontalLight, dark: horizontalDark, mono: horizontalMono, ratio: 310 / 891 },
  logo: { light: primaryLight, dark: primaryDark, mono: primaryMono, ratio: 1080 / 1000 },
};

export function IQDIBrand({ variant = 'symbol', size = 40, tone = 'auto', label = IQDI_BRAND_LABEL, decorative = false, className }: {
  variant?: IQDIBrandVariant;
  /** Rendered width in CSS px; height follows the artwork's aspect ratio (no stretching). */
  size?: number;
  tone?: 'auto' | 'light' | 'dark' | 'monochrome';
  label?: string;
  /** True when adjacent text already names the product (e.g. the header), so screen readers do not hear it twice. */
  decorative?: boolean;
  className?: string;
}) {
  const { resolvedTheme } = useTheme();
  const art = ART[variant];
  const t = tone === 'auto' ? resolvedTheme : tone;
  const src = t === 'monochrome' ? art.mono : t === 'dark' ? art.dark : art.light;
  return (
    <img
      className={`iqdi-brand iqdi-brand--${variant}${className ? ` ${className}` : ''}`}
      src={src}
      width={size}
      height={Math.round(size * art.ratio)}
      alt={decorative ? '' : label}
      aria-hidden={decorative ? true : undefined}
      data-tone={t}
      decoding="async"
      draggable={false}
    />
  );
}
